// Generate returns a map of relative path to file content. An unknown format
// returns an empty map.
func Generate(format string) map[string]string {
	all := map[string]string{
		"sigma/php2shell_startup_oom.yml":     sigmaOOM,
		"sigma/php2shell_worker_crash.yml":    sigmaCrash,
		"sigma/php2shell_large_post.yml":      sigmaLargePost,
		"sigma/php2shell_session_cookie.yml":  sigmaCookie,
		"sigma/php2shell_web_shell_child.yml": sigmaShellChild,
		"modsecurity/php2shell.conf":          modsec,
		"nginx/php2shell.conf":                nginx,
		"yara/php2shell_webshell.yar":         yara,
		"siem/php2shell.kql":                  kql,
		"siem/php2shell.spl":                  spl,
		"README.md":                           readme,
	}
	switch strings.ToLower(format) {
	case "", "all":
		return all
	case "sigma":
		return filter(all, "sigma/")
	case "modsecurity", "modsec":
		return filter(all, "modsecurity/")
	case "nginx":
		return filter(all, "nginx/")
	case "yara":
		return filter(all, "yara/")
	case "kql":
		return filter(all, "siem/php2shell.kql")
	case "splunk", "spl":
		return filter(all, "siem/php2shell.spl")
	}
	return map[string]string{}
}

func filter(all map[string]string, prefix string) map[string]string {
	out := map[string]string{}
	for k, v := range all {
		if strings.HasPrefix(k, prefix) {
			out[k] = v
		}
	}
	return out
}


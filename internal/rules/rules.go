const kql = `// php2shell-audit - Microsoft Sentinel / Defender KQL
// Adapt table and column names to your connector.

// 1) PHP OOM during request startup (Apache/PHP error log via Syslog).
Syslog
| where TimeGenerated > ago(7d)
| where SyslogMessage has "Allowed memory size of" and SyslogMessage has "in Unknown on line 0"
| extend ClientIP = extract(@"\\[client ([^\\]:]+)", 1, SyslogMessage)
| summarize Count=count(), First=min(TimeGenerated), Last=max(TimeGenerated), Samples=make_set(SyslogMessage, 5) by Host, ClientIP
| order by Count desc

// 2) Worker crashes.
Syslog
| where TimeGenerated > ago(7d)
| where SyslogMessage has_any ("AH00052", "exited on signal 11", "exited on signal 6", "SIGSEGV")
| summarize Count=count(), First=min(TimeGenerated), Last=max(TimeGenerated) by Host, ProcessName

// 3) Web worker spawned a shell or transfer tool.
DeviceProcessEvents
| where Timestamp > ago(7d)
| where InitiatingProcessFileName in~ ("apache2", "httpd", "php-fpm", "php-cgi", "frankenphp", "litespeed")
| where FileName in~ ("sh", "bash", "dash", "zsh", "nc", "ncat", "socat", "curl", "wget")
| project Timestamp, DeviceName, InitiatingProcessFileName, InitiatingProcessId, FileName, ProcessCommandLine

// 4) Egress from a web worker to an unusual destination.
DeviceNetworkEvents
| where Timestamp > ago(7d)
| where InitiatingProcessFileName in~ ("apache2", "httpd", "php-fpm", "php-cgi", "sh", "bash", "nc", "socat")
| where RemoteIPType == "Public" and RemotePort !in (80, 443, 53)
| project Timestamp, DeviceName, InitiatingProcessFileName, RemoteIP, RemotePort, RemoteUrl

// 5) New PHP file in an upload or cache directory.
DeviceFileEvents
| where Timestamp > ago(7d)
| where ActionType == "FileCreated"
| where FileName endswith ".php" or FileName endswith ".phtml"
| where FolderPath has_any ("/uploads/", "/cache/", "/tmp/", "/files/")
| project Timestamp, DeviceName, FolderPath, FileName, InitiatingProcessFileName
`

